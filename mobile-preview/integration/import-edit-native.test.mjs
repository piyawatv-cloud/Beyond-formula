// Synthetic local file, disposable browser profile and preview data only.
import assert from 'node:assert/strict';
import test from 'node:test';
import {createServer} from 'node:http';
import {readFile,writeFile,mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const {actualBrowser,browserValue,waitForDocument}=await import(process.env.FORMULA_TEST_BROWSER_HELPER_URL||new URL('../../_IT-handoff/formula-studio/tests/helpers/chat-journal-browser.mjs',import.meta.url).href);
const pause=ms=>new Promise(r=>setTimeout(r,ms));
test('editing an existing brief warns before importing partial data',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'formula-import-edit-'));t.after(()=>rm(dir,{recursive:true,force:true}));
 const file=join(dir,'synthetic.csv');await writeFile(file,'customer_name,ลูกค้าใหม่');
 const html=await readFile(new URL('../index.html',import.meta.url));
 const server=createServer((_req,res)=>{res.writeHead(200,{'content-type':'text/html; charset=utf-8'});res.end(html)});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));t.after(()=>{server.closeAllConnections();return new Promise(resolve=>server.close(resolve))});
 const origin='http://127.0.0.1:'+server.address().port+'/';const browser=await actualBrowser(t,origin);assert.ok(browser);await waitForDocument(browser,origin);await browser.send('Page.enable');
 await browser.send('Runtime.evaluate',{userGesture:true,expression:`document.querySelector('[data-open="A00001"]').click();document.querySelector('[data-action="edit"]').click()`});
 const doc=await browser.send('DOM.getDocument');const match=await browser.send('DOM.querySelector',{nodeId:doc.result.root.nodeId,selector:'#csv-file'});
 const choose=()=>browser.send('DOM.setFileInputFiles',{nodeId:match.result.nodeId,files:[file]});
 let pending=choose();for(let i=0;i<100&&!browser.dialogs.length;i++)await pause(20);
 assert.equal(browser.dialogs[0]?.type,'confirm');assert.match(browser.dialogs[0].message,/ไม่มีในไฟล์/);assert.match(browser.dialogs[0].message,/สาร/);
 await browser.send('Page.handleJavaScriptDialog',{accept:false});await pending;
 assert.equal(await browserValue(browser,"document.querySelector('#f-customer').value"),'ลูกค้าจำลอง A');
 assert.equal(await browserValue(browser,"document.querySelector('#brief-name-0').value"),'สารตัวอย่าง');
 pending=choose();for(let i=0;i<100&&browser.dialogs.length<2;i++)await pause(20);
 assert.equal(browser.dialogs[1]?.type,'confirm');await browser.send('Page.handleJavaScriptDialog',{accept:true});await pending;
 for(let i=0;i<100&&!(await browserValue(browser,"document.querySelector('#csv-status').textContent.includes('อ่านไฟล์แล้ว')"));i++)await pause(20);
 assert.equal(await browserValue(browser,"document.querySelector('#f-customer').value"),'ลูกค้าใหม่');
 assert.equal(await browserValue(browser,"document.querySelector('#f-brand').value"),'แบรนด์ตัวอย่าง A');
 assert.equal(await browserValue(browser,"!!document.querySelector('#brief-name-0')"),false);
});
