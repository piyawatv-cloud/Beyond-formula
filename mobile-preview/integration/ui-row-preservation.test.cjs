'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const model=html.match(/<script id="model">([\s\S]*?)<\/script>/)[1];
const readRows=html.match(/const readRows=\(\)=>[\s\S]*?;const drawRows=/);
assert.ok(readRows,'brief row reader not found');
const formulaRows=html.match(/let rows=j\.rows\.map\(\(r,i\)=>[\s\S]*?\.filter\(Boolean\);if\(String\(f\.get\('newIngredient'\)/);
assert.ok(formulaRows,'formula row reader not found');
const original={name:'สารจำลอง',w:100,p:50,actual:50,fda:{status:'fixture'},extra:'keep'};
const values={name:'สารจำลอง',w:'100',o:'',p:'50',note:''};
const ctx={module:{exports:{}},draftRows:[original],$:id=>id.includes('hero')||id.includes('remove')?{checked:false}:{value:values[id.match(/^brief-(.*)-0$/)[1]]}};
vm.createContext(ctx);vm.runInContext(model,ctx);vm.runInContext(readRows[0].replace(/;const drawRows=$/,';globalThis.readFixtureRows=readRows;'),ctx);
const rows=JSON.parse(JSON.stringify(ctx.readFixtureRows()));
assert.deepEqual(rows,[original],'opening and saving a brief must preserve untouched numeric and hidden ingredient fields');
values.note='แก้หมายเหตุ';const updated=JSON.parse(JSON.stringify(ctx.readFixtureRows()));
assert.equal(updated[0].w,100);assert.equal(updated[0].p,50);assert.equal(updated[0].note,'แก้หมายเหตุ');assert.deepEqual(updated[0].fda,original.fda);
 values.note='';values.w='120';const briefChanged=JSON.parse(JSON.stringify(ctx.readFixtureRows()));
 assert.equal(briefChanged[0].actual,60,'brief must update the stored illustrative calculation after weight changes');
 values.w='100';values.p='';const briefIncomplete=JSON.parse(JSON.stringify(ctx.readFixtureRows()));
 assert.equal(briefIncomplete[0].actual,null,'missing concentration must not leave an old calculation');
 values.p='50';
values.note='';ctx.j={rows:[original]};ctx.f={get:key=>values[key.replace(/-0$/,'')],has:()=>false};
vm.runInContext('globalThis.formulaFixtureRows=()=>{'+formulaRows[0].replace(/if\(String\(f\.get\('newIngredient'\)$/,'')+'return rows}',ctx);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.formulaFixtureRows())),[original],'formula editor must not rewrite untouched row types');
values.w='120';const changedFormula=JSON.parse(JSON.stringify(ctx.formulaFixtureRows()));assert.equal(changedFormula[0].w,'120');assert.equal(changedFormula[0].p,50);assert.equal(changedFormula[0].actual,60);assert.equal(changedFormula[0].extra,'keep');
console.log('PASS: brief and formula readers preserve untouched numeric and hidden fields');
